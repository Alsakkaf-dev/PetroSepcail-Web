#!/usr/bin/env node
// PC-08 (FR-PC08-001) — mechanical token pipeline: extracts the design-token
// rule blocks verbatim from the site's own assets/css/styles.css and writes
// packages/ui/src/tokens/tokens.generated.css. Do not hand-edit the output;
// re-run this script whenever styles.css's :root block changes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(repoRoot, "assets/css/styles.css");
const outPath = path.join(repoRoot, "packages/ui/src/tokens/tokens.generated.css");

const css = readFileSync(sourcePath, "utf8");

/** Extract a top-level rule/at-rule starting at the first match of `selector`,
 * by brace-balance from its opening `{` — works for nested @media blocks too. */
function extractBlock(source, selector) {
  const start = source.indexOf(selector);
  if (start === -1) {
    throw new Error(`generate-ui-tokens: selector not found in styles.css: ${selector}`);
  }
  const braceStart = source.indexOf("{", start);
  let depth = 0;
  let i = braceStart;
  for (; i < source.length; i += 1) {
    if (source[i] === "{") depth += 1;
    else if (source[i] === "}") {
      depth -= 1;
      if (depth === 0) break;
    }
  }
  return source.slice(start, i + 1).trim();
}

const rootBlock = extractBlock(css, ":root {");
const langEnBlock = extractBlock(css, 'html[lang="en"] {');
const wideBreakpointBlock = extractBlock(css, "@media (min-width: 160em) {");

const output = `/* AUTO-GENERATED by scripts/generate-ui-tokens.mjs from assets/css/styles.css.
 * Do not hand-edit — re-run \`npm run tokens:generate -w @petrospecial/ui\`.
 * PC-08 (FR-PC08-001): every packages/ui component must reference these
 * custom properties; no literal hex/px where a token exists here. */

${rootBlock}

/* English mode: Latin-led display type (site behavior, PC-07 §2). */
${langEnBlock}

/* 4K comfort breakpoint: cap ultra-wide container width. */
${wideBreakpointBlock}
`;

writeFileSync(outPath, output, "utf8");
console.log(`generate-ui-tokens: wrote ${path.relative(repoRoot, outPath)}`);
